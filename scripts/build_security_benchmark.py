def build_cases() -> List[Dict]:
    _counter['n'] = 0
    cases = (direct_prompt_injection() + system_override() + prompt_secret_extraction()
             + indirect_prompt_injection() + embedded_document_injection())
    return cases + controls()


def build_document() -> Dict:
    cases = build_cases()
    attacks = [c for c in cases if c['kind'] == 'attack']
    return {
        'schema_version': SCHEMA_VERSION,
        'description': (
            'Dimension 3 adversarial security benchmark. Separate from the Dimension 1 '
            'retrieval benchmark (data/evaluation/). Attack cases carry a unique marker '
            'or a leak target so success can be decided by string checks, not an LLM judge.'
        ),
        'counts': {
            'attacks': len(attacks),
            'benign_controls': len(cases) - len(attacks),
            'by_category': {cat: sum(1 for c in attacks if c['category'] == cat) for cat in CATEGORIES},
        },
        'cases': cases,
    }


def render(doc: Dict) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + '\n'


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--output', default=DEFAULT_OUTPUT)
    ap.add_argument('--check', action='store_true', help='fail if the file on disk differs')
    args = ap.parse_args(argv)
    text = render(build_document())
    if args.check:
        current = open(args.output, encoding='utf-8').read() if os.path.exists(args.output) else None
        if current != text:
            print(f'{args.output} is out of date; run without --check to regenerate.', file=sys.stderr)
            return 1
        print('up to date')
        return 0
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote {args.output}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
